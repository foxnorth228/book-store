import "@app/theme/theme.css";

import { DefaultLayout } from "@app/layouts/DefaultLayout";
import { I18nProvider } from "next-i18next/client";
import { lang } from "next/root-params";
import { Toaster } from "@org/ui";
import { SettingsProvider } from "@app/providers/settings-provider";

import { generateI18nStaticParams, getResources, getT } from "@/i18n.server";

export const metadata = {
  title: "Welcome to web-store",
  description: "Generated by create-nx-workspace",
};

export function generateStaticParams() {
  return generateI18nStaticParams();
}

export default async function MainLayout(props: LayoutProps<"/[lang]">) {
  const locale = await lang();
  const { i18n } = await getT();
  const resources = getResources(i18n);

  return (
    <html lang={locale}>
      <I18nProvider language={locale} resources={resources}>
        <body>
          <DefaultLayout>{props.children}</DefaultLayout>
          <Toaster position={"top-center"} />
          <SettingsProvider />
        </body>
      </I18nProvider>
    </html>
  );
}
